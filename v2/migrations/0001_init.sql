-- 0001_init — Po'lat / Ziyo Family bazasining PostgreSQL'dagi boshlang'ich sxemasi.
--
-- Eski SQLite sxemasi (server/schema.sql + server/db.js'dagi ~35 ta ALTER
-- migratsiya + server/printer.js'dagi print_jobs) shu yerda BITTA toza sxemaga
-- yig'ilgan. SQLite'dan farqlari (ataylab):
--   * vaqtlar   — TEXT ISO o'rniga TIMESTAMPTZ (UTC saqlanadi, Toshkent vaqti
--                 so'rovda `AT TIME ZONE 'Asia/Tashkent'` bilan olinadi);
--   * sanalar   — expense_date / res_date -> DATE, res_time -> TIME;
--   * 0/1       — BOOLEAN;
--   * pul       — BIGINT (so'm, butun son; kasr so'm yo'q);
--   * koordinata— DOUBLE PRECISION;
--   * SQLite'da ALTER bilan qo'shib bo'lmagan FOREIGN KEY'lar endi bor
--     (notifications.order_item_id, menu_items.inventory_item_id/parent_item_id,
--     *.cash_shift_id, customer_orders.assigned_courier_id, order_items.cancelled_by);
--   * biznes qoidalari CHECK sifatida bazaning o'zida (narx >= 0, miqdor > 0,
--     ombor qoldig'i >= 0, to'lov summalari mosligi va h.k.) — kod xato qilsa
--     ham baza noto'g'ri ma'lumotni qabul qilmaydi.
-- ID'lar `GENERATED BY DEFAULT AS IDENTITY` — SQLite'dan ko'chirishda eski
-- ID'lar saqlanadi (chek raqamlari o'zgarmaydi), keyin sequence'lar suriladi.

-- ============================================================ Xodimlar
CREATE TABLE users (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username         TEXT        NOT NULL UNIQUE CHECK (length(username) BETWEEN 1 AND 64),
  password_hash    TEXT        NOT NULL,
  password_salt    TEXT        NOT NULL,
  role             TEXT        NOT NULL CHECK (role IN ('admin', 'waiter', 'chef', 'courier', 'kassir')),
  full_name        TEXT,
  is_active        BOOLEAN     NOT NULL DEFAULT TRUE,
  -- Oshirilsa shu xodimning barcha cookie'lari darhol bekor bo'ladi
  -- (eski tizimdagi "sessiyani bekor qilish yo'q" muammosining yechimi).
  session_version  INTEGER     NOT NULL DEFAULT 1,
  last_login_at    TIMESTAMPTZ,
  last_login_ip    TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE login_attempts (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username    TEXT        NOT NULL,
  success     BOOLEAN     NOT NULL,
  ip          TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_login_attempts_username ON login_attempts (username, created_at);

CREATE TABLE audit_log (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action        TEXT        NOT NULL,
  entity_type   TEXT        NOT NULL,
  entity_id     BIGINT      NOT NULL,
  old_value     JSONB,
  new_value     JSONB,
  performed_by  BIGINT      REFERENCES users (id),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_log_entity ON audit_log (entity_type, entity_id);
CREATE INDEX idx_audit_log_user ON audit_log (performed_by);
CREATE INDEX idx_audit_log_created ON audit_log (created_at);

-- ============================================================ Sozlamalar
CREATE TABLE settings (
  key    TEXT PRIMARY KEY,
  value  TEXT
);

-- ============================================================ Zallar va stollar
CREATE TABLE table_zones (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT        NOT NULL,
  sort_order  INTEGER     NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE tables (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT        NOT NULL,
  sort_order  INTEGER     NOT NULL DEFAULT 0,
  is_active   BOOLEAN     NOT NULL DEFAULT TRUE,
  zone_id     BIGINT      REFERENCES table_zones (id),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_tables_zone ON tables (zone_id);

-- ============================================================ Ombor
CREATE TABLE inventory_categories (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT        NOT NULL,
  sort_order  INTEGER     NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE inventory_items (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                 TEXT        NOT NULL,
  unit                 TEXT        NOT NULL DEFAULT 'dona',
  quantity             INTEGER     NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  low_stock_threshold  INTEGER     NOT NULL DEFAULT 0 CHECK (low_stock_threshold >= 0),
  cost_price           BIGINT      NOT NULL DEFAULT 0 CHECK (cost_price >= 0),
  sale_price           BIGINT      NOT NULL DEFAULT 0 CHECK (sale_price >= 0),
  volume               TEXT,
  category_id          BIGINT      REFERENCES inventory_categories (id),
  image_url            TEXT,
  is_active            BOOLEAN     NOT NULL DEFAULT TRUE,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_inventory_items_category ON inventory_items (category_id);

-- ============================================================ Menyu
CREATE TABLE menu_categories (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                    TEXT        NOT NULL,
  sort_order              INTEGER     NOT NULL DEFAULT 0,
  is_active               BOOLEAN     NOT NULL DEFAULT TRUE,
  require_inventory_link  BOOLEAN     NOT NULL DEFAULT FALSE,
  created_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE menu_items (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id        BIGINT      NOT NULL REFERENCES menu_categories (id),
  name               TEXT        NOT NULL,
  description        TEXT,
  image_url          TEXT,
  volume             TEXT,
  price              BIGINT      NOT NULL CHECK (price >= 0),
  cost_price         BIGINT      CHECK (cost_price >= 0),
  is_available       BOOLEAN     NOT NULL DEFAULT TRUE,
  is_active          BOOLEAN     NOT NULL DEFAULT TRUE,
  sort_order         INTEGER     NOT NULL DEFAULT 0,
  parent_item_id     BIGINT      REFERENCES menu_items (id),
  inventory_item_id  BIGINT      REFERENCES inventory_items (id),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (parent_item_id IS NULL OR parent_item_id <> id)
);
CREATE INDEX idx_menu_items_category ON menu_items (category_id);
CREATE INDEX idx_menu_items_parent ON menu_items (parent_item_id);
CREATE INDEX idx_menu_items_inventory ON menu_items (inventory_item_id);

-- ============================================================ Kassa smenalari
CREATE TABLE cash_shifts (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opened_by      BIGINT      NOT NULL REFERENCES users (id),
  opened_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  opening_cash   BIGINT      NOT NULL DEFAULT 0 CHECK (opening_cash >= 0),
  closed_by      BIGINT      REFERENCES users (id),
  closed_at      TIMESTAMPTZ,
  expected_cash  BIGINT,
  actual_cash    BIGINT      CHECK (actual_cash >= 0),
  variance       BIGINT,
  status         TEXT        NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  note           TEXT,
  CHECK ((status = 'open') = (closed_at IS NULL))
);
CREATE INDEX idx_cash_shifts_opened_by ON cash_shifts (opened_by);
CREATE INDEX idx_cash_shifts_status ON cash_shifts (status);
-- Bitta kassirda bir vaqtda faqat BITTA ochiq smena (eski tizimda faqat kod tekshirardi).
CREATE UNIQUE INDEX idx_cash_shifts_one_open_per_user ON cash_shifts (opened_by) WHERE status = 'open';

-- ============================================================ Stol buyurtmalari (dine-in)
CREATE TABLE orders (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id        BIGINT      NOT NULL REFERENCES tables (id),
  status          TEXT        NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  opened_by       BIGINT      NOT NULL REFERENCES users (id),
  opened_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  closed_by       BIGINT      REFERENCES users (id),
  closed_at       TIMESTAMPTZ,
  total_amount    BIGINT      CHECK (total_amount >= 0),
  note            TEXT,
  bill_requested  BOOLEAN     NOT NULL DEFAULT FALSE,
  payment_method  TEXT        CHECK (payment_method IN ('cash', 'card', 'mixed')),
  cash_amount     BIGINT      CHECK (cash_amount >= 0),
  card_amount     BIGINT      CHECK (card_amount >= 0),
  cash_shift_id   BIGINT      REFERENCES cash_shifts (id)
);
-- Bitta stolda faqat bitta ochiq buyurtma.
CREATE UNIQUE INDEX idx_orders_one_open_per_table ON orders (table_id) WHERE status = 'open';
CREATE INDEX idx_orders_table ON orders (table_id);
CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_orders_closed_at ON orders (closed_at);
CREATE INDEX idx_orders_cash_shift ON orders (cash_shift_id);
-- Kassada to'lov kutayotgan hisoblar (bill_requested + closed + to'lov turisiz).
CREATE INDEX idx_orders_pending_payment ON orders (closed_at)
  WHERE status = 'closed' AND bill_requested AND payment_method IS NULL;

CREATE TABLE order_items (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id       BIGINT      NOT NULL REFERENCES orders (id),
  menu_item_id   BIGINT      NOT NULL REFERENCES menu_items (id),
  name_snapshot  TEXT        NOT NULL,
  unit_price     BIGINT      NOT NULL CHECK (unit_price >= 0),
  quantity       INTEGER     NOT NULL DEFAULT 1 CHECK (quantity > 0),
  subtotal       BIGINT      NOT NULL CHECK (subtotal >= 0),
  added_by       BIGINT      NOT NULL REFERENCES users (id),
  status         TEXT        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'cancelled')),
  note           TEXT        NOT NULL DEFAULT '',
  sent_at        TIMESTAMPTZ,
  ready_at       TIMESTAMPTZ,
  picked_up_at   TIMESTAMPTZ,
  cancelled_by   BIGINT      REFERENCES users (id),
  cancelled_at   TIMESTAMPTZ,
  cancel_reason  TEXT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_menu_item ON order_items (menu_item_id);
-- Oshxona ekrani: yuborilgan, lekin hali tayyor bo'lmagan taomlar.
CREATE INDEX idx_order_items_kitchen ON order_items (sent_at)
  WHERE status = 'active' AND sent_at IS NOT NULL AND ready_at IS NULL;

CREATE TABLE print_requests (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    BIGINT      NOT NULL REFERENCES orders (id),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  printed_at  TIMESTAMPTZ,
  printed_by  TEXT
);
CREATE INDEX idx_print_requests_pending ON print_requests (printed_at);

