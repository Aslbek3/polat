);
CREATE INDEX idx_manual_bills_created ON manual_bills (created_at);
CREATE INDEX idx_manual_bills_cash_shift ON manual_bills (cash_shift_id);

CREATE TABLE manual_bill_items (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  manual_bill_id  BIGINT  NOT NULL REFERENCES manual_bills (id),
  name            TEXT    NOT NULL,
  unit_price      BIGINT  NOT NULL CHECK (unit_price >= 0),
