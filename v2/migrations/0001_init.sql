  customer_id  BIGINT      REFERENCES customers (id),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_reservations_date ON reservations (res_date);
CREATE INDEX idx_reservations_customer ON reservations (customer_id);

-- ============================================================ Onlayn buyurtmalar (sayt)
CREATE TABLE customer_orders (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name             TEXT             NOT NULL,
  phone                 TEXT             NOT NULL,
  fulfillment           TEXT             NOT NULL DEFAULT 'pickup' CHECK (fulfillment IN ('pickup', 'delivery')),
  address               TEXT,
  location_lat          DOUBLE PRECISION CHECK (location_lat BETWEEN -90 AND 90),
  location_lng          DOUBLE PRECISION CHECK (location_lng BETWEEN -180 AND 180),
  note                  TEXT,
  -- total_amount = taomlar + delivery_fee (2026-10-23 qarori).
  total_amount          BIGINT           NOT NULL CHECK (total_amount >= 0),
  delivery_distance_km  DOUBLE PRECISION CHECK (delivery_distance_km >= 0),
  delivery_fee          BIGINT           CHECK (delivery_fee >= 0),
  -- 'completed' = oshxonada tayyor, "yetkazildi" EMAS (delivered_at alohida).
  status                TEXT             NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'confirmed', 'completed', 'cancelled')),
  cancel_reason         TEXT,
  assigned_courier_id   BIGINT           REFERENCES users (id),
  delivered_at          TIMESTAMPTZ,
  customer_id           BIGINT           REFERENCES customers (id),
  created_at            TIMESTAMPTZ      NOT NULL DEFAULT now()
);
CREATE INDEX idx_customer_orders_status ON customer_orders (status);
CREATE INDEX idx_customer_orders_customer ON customer_orders (customer_id);
CREATE INDEX idx_customer_orders_created ON customer_orders (created_at);
CREATE INDEX idx_customer_orders_courier ON customer_orders (assigned_courier_id);

CREATE TABLE customer_order_items (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_order_id  BIGINT  NOT NULL REFERENCES customer_orders (id),
  menu_item_id       BIGINT  REFERENCES menu_items (id),
  name_snapshot      TEXT    NOT NULL,
  unit_price         BIGINT  NOT NULL CHECK (unit_price >= 0),
  quantity           INTEGER NOT NULL CHECK (quantity > 0),
  subtotal           BIGINT  NOT NULL CHECK (subtotal >= 0)
);
CREATE INDEX idx_customer_order_items_order ON customer_order_items (customer_order_id);

-- ============================================================ Ombor harakatlari
CREATE TABLE inventory_movements (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventory_item_id       BIGINT      NOT NULL REFERENCES inventory_items (id),
  delta                   INTEGER     NOT NULL CHECK (delta <> 0),
  reason                  TEXT        NOT NULL CHECK (reason IN ('restock', 'adjustment', 'waste', 'stocktake', 'order', 'return')),
  note                    TEXT,
  order_item_id           BIGINT      REFERENCES order_items (id),
  customer_order_item_id  BIGINT      REFERENCES customer_order_items (id),
  created_by              BIGINT      REFERENCES users (id),
  created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (order_item_id IS NULL OR customer_order_item_id IS NULL)
);
CREATE INDEX idx_inventory_movements_item ON inventory_movements (inventory_item_id, created_at);

-- ============================================================ Qo'lda chek (kassir)
CREATE TABLE manual_bills (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_by      BIGINT      NOT NULL REFERENCES users (id),
