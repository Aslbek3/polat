-- ============================================================ Oshxona cheklari
CREATE TABLE kitchen_tickets (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id           BIGINT      REFERENCES orders (id),
  customer_order_id  BIGINT      REFERENCES customer_orders (id),
  table_name         TEXT        NOT NULL,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  printed_at         TIMESTAMPTZ,
  -- Chek yo stolga, yo onlayn buyurtmaga tegishli (ikkalasi emas, hech biri emas emas).
  CHECK ((order_id IS NULL) <> (customer_order_id IS NULL))
);
CREATE INDEX idx_kitchen_tickets_pending ON kitchen_tickets (printed_at);

CREATE TABLE kitchen_ticket_items (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kitchen_ticket_id  BIGINT  NOT NULL REFERENCES kitchen_tickets (id),
  name_snapshot      TEXT    NOT NULL,
  quantity           INTEGER NOT NULL CHECK (quantity > 0),
  note               TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX idx_kitchen_ticket_items_ticket ON kitchen_ticket_items (kitchen_ticket_id);

-- Printer agentiga WebSocket orqali yuboriladigan cheklar navbati.
-- printed: 0 = kutilmoqda, 1 = chop etildi, 2 = muddati o'tdi / urinishlar tugadi.
CREATE TABLE print_jobs (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payload       JSONB       NOT NULL,
  printed       SMALLINT    NOT NULL DEFAULT 0 CHECK (printed IN (0, 1, 2)),
  sent_count    INTEGER     NOT NULL DEFAULT 0 CHECK (sent_count >= 0),
  last_sent_at  TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_print_jobs_pending ON print_jobs (id) WHERE printed = 0;
